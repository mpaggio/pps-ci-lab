public class Sapo2k3 {
    private final String name;
    private final String surname;

    public Sapo2k3(final String name, final String surname) {
        this.name = name;
        this.surname = surname;
    }

    public String getName() {
        return this.name;
    }

    public String getSurname() {
        return this.surname;
    }
}